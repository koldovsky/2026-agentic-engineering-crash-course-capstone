// Vision gate: every requirement tagged `vision-verify` needs at least one recorded clip
// that the vision-verify workflow judged met and readable.
//
// Reads the `vision` verdicts the workflow writes into docs/qa/**/manifest.json and writes
// docs/qa/vision-report.json + .md, the artifacts check-acceptance-methods validates.
//
// Usage: node scripts/check-vision.mjs
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { isAbsolute, join } from "node:path";

const root = process.cwd();
const PATHS = {
  requirements: "docs/requirements.md",
  specsDir: "openspec/specs",
  qaDir: "docs/qa",
  json: "docs/qa/vision-report.json",
  md: "docs/qa/vision-report.md",
};
const METHOD = "vision-verify";

const read = (rel) => {
  try {
    return readFileSync(join(root, rel), "utf8");
  } catch {
    return null;
  }
};

function* walk(rel) {
  let entries = [];
  try {
    entries = readdirSync(join(root, rel));
  } catch {
    return;
  }
  for (const entry of entries) {
    if (entry === "node_modules" || entry.startsWith(".")) continue;
    const child = `${rel}/${entry}`;
    let isDir = false;
    try {
      isDir = statSync(join(root, child)).isDirectory();
    } catch {
      continue;
    }
    if (isDir) yield* walk(child);
    else yield child;
  }
}

// Same product-code roots and extensions as gate-status, so both agree on NOT-EARNED.
const IMPL_DIRS = ["frontend/src", "backend/src/main", "app", "src", "lib", "pages", "components", "server", "api"];
const IMPL_EXT = /\.(mjs|cjs|js|jsx|ts|tsx|vue|svelte|py|go|rb|rs|java|cs|php)$/i;
const productCode = IMPL_DIRS.some((d) => existsSync(join(root, d)) && [...walk(d)].some((f) => IMPL_EXT.test(f) && !/\.(test|spec)\./.test(f)));

// Tagged rows are found the way check-acceptance-methods finds them (any phase, categorized ids,
// case-insensitive token, spec lines too), because its artifact check reads one file for all of them.
const ID_RE = /\b(?:FR|NFR|TC|BC)-(?:[A-Z0-9]+-)?\d+\b/g;
const tagged = (line) => new RegExp(`\\b${METHOD}\\b`, "i").test(line);
const requirementsText = read(PATHS.requirements);
const declared = new Set();
for (const line of (requirementsText ?? "").split("\n")) {
  const m = line.match(/^\|\s*((?:FR|NFR|TC|BC)-(?:[A-Z0-9]+-)?\d+)\s*\|/);
  if (m && tagged(line)) declared.add(m[1]);
}
for (const file of walk(PATHS.specsDir)) {
  if (!file.endsWith("/spec.md")) continue;
  for (const line of (read(file) ?? "").split("\n")) if (tagged(line)) for (const id of line.match(ID_RE) ?? []) declared.add(id);
}

const clips = [];
const unreadable = [];
for (const file of walk(PATHS.qaDir)) {
  if (!file.endsWith("/manifest.json")) continue;
  let data = null;
  try {
    data = JSON.parse(read(file));
  } catch {
    unreadable.push(file);
    continue;
  }
  for (const r of data?.results ?? []) {
    const onDisk = (rel) => {
      if (typeof rel !== "string" || !rel) return false;
      try {
        return statSync(isAbsolute(rel) ? rel : join(root, rel)).size > 0;
      } catch {
        return false;
      }
    };
    clips.push({
      manifest: file,
      id: r.id ?? "(no id)",
      proof: String(r.proof ?? "").match(ID_RE) ?? [],
      asserted: r.asserted === true,
      filesOnDisk: onDisk(r.video) && onDisk(r.screenshot),
      vision: r.vision ?? null,
    });
  }
}

const judgedMet = (c) => c.vision?.met === true && c.vision?.readable === true;
const unmet = clips.filter((c) => c.vision && !judgedMet(c));
const requirements = [...declared].sort().map((id) => {
  const proving = clips.filter((c) => c.asserted && c.filesOnDisk && judgedMet(c) && c.proof.includes(id)).map((c) => c.id);
  return { id, clips: proving, met: proving.length > 0 };
});
const unproven = requirements.filter((r) => !r.met).map((r) => r.id);

let result;
if (requirementsText === null) result = productCode ? "FAIL" : "SKIP-pending";
else if (unreadable.length || unmet.length) result = "FAIL";
else if (declared.size === 0) result = productCode ? "NOT-EARNED" : "SKIP-pending";
else if (clips.length === 0 && !productCode) result = "SKIP-pending";
else if (unproven.length) result = "NOT-EARNED";
else result = "PASS";
const status = { PASS: "passed", FAIL: "failed", "NOT-EARNED": "not-earned", "SKIP-pending": "skip-pending" }[result];
const met = result === "PASS";

const report = {
  generatedBy: "scripts/check-vision.mjs",
  status,
  met,
  requirements,
  unreadableManifests: unreadable,
  clips: clips.map((c) => ({ manifest: c.manifest, id: c.id, proof: c.proof, asserted: c.asserted, filesOnDisk: c.filesOnDisk, vision: c.vision })),
};
const yes = (b) => (b ? "yes" : "**no**");
const md = `# Vision Report (generated by scripts/check-vision.mjs — do not hand-edit)

The vision-verify workflow writes its per-clip verdicts into the recording manifests and
\`docs/qa/vision-verdicts.md\`. This report joins them to the requirements tagged ${METHOD}.

Result: ${result}
met: ${met}

| Requirement | Clips judged met | Met |
|---|---|---|
${requirements.map((r) => `| ${r.id} | ${r.clips.join(", ") || "-"} | ${yes(r.met)} |`).join("\n")}

| Clip | Manifest | Proves | Asserted | Files on disk | Met | Readable |
|---|---|---|---|---|---|---|
${clips.map((c) => `| ${c.id} | ${c.manifest} | ${c.proof.join(", ") || "-"} | ${yes(c.asserted)} | ${yes(c.filesOnDisk)} | ${c.vision ? yes(c.vision.met === true) : "-"} | ${c.vision ? yes(c.vision.readable === true) : "-"} |`).join("\n")}
${unreadable.length ? `\nUnreadable manifests: ${unreadable.join(", ")}\n` : ""}`;
mkdirSync(join(root, PATHS.qaDir), { recursive: true });
writeFileSync(join(root, PATHS.json), `${JSON.stringify(report, null, 2)}\n`);
writeFileSync(join(root, PATHS.md), md);

if (requirementsText === null) console.error(`${result === "FAIL" ? "FAIL" : "SKIP"}  [vision] ${PATHS.requirements} not found`);
for (const f of unreadable) console.error(`FAIL  [vision] ${f} is not valid JSON`);
for (const c of unmet) console.error(`FAIL  [vision] ${c.id} (${c.manifest}): judged ${JSON.stringify(c.vision)}`);
if (requirementsText !== null && declared.size === 0) console.error(`${result === "NOT-EARNED" ? "NOT-EARNED" : "SKIP"}  [vision] no requirement is tagged ${METHOD}`);
for (const id of unproven) console.error(`${result === "SKIP-pending" ? "SKIP" : "NOT-EARNED"}  [vision] ${id} has no recorded clip judged met and readable`);
console.log(`\nScope: ${declared.size} requirement(s) tagged ${METHOD}, ${clips.length} clip(s)`);
console.log(`wrote ${PATHS.json} and ${PATHS.md}`);
console.log(`Result: ${result}`);
process.exit(result === "FAIL" || result === "NOT-EARNED" ? 1 : 0);
